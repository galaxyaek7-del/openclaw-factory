"""Distribution dashboard: operational state and commercial evidence, kept apart.

Built only from recorded files: the offer registry, the campaign job ledger,
platform readiness and the REAL metrics ledger. An empty section says so; no
number is shown without its source.
"""
from __future__ import annotations

import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from social_distribution import tracking

ROOT = Path(__file__).resolve().parent.parent
OUT_JSON = ROOT / "data" / "distribution_dashboard.json"
OUT_MD = ROOT / "docs" / "distribution" / "DISTRIBUTION_DASHBOARD.md"


def build(offers_doc: dict, jobs: list, readiness: dict, metrics: list | None = None) -> dict:
    offers = offers_doc["offers"]
    metrics = [m for m in (metrics or []) if m.get("environment") == "REAL"]
    stuck = [j["job_id"] for j in jobs if j["state"] in ("NEEDS_RECONCILIATION", "FAILED", "RATE_LIMITED", "FAILED_RETRYABLE")]
    blocked_reasons = Counter(r for o in offers if o["eligibility"]["status"] != "ELIGIBLE" for r in o["eligibility"]["reasons"])
    qa_fail = Counter(i for j in jobs if j["state"] == "QA_FAILED" for i in (j.get("qa_issues") or [j.get("reason")]))
    commercial = {}
    for m in metrics:
        commercial.setdefault(m["metric"], []).append({"value": m["value"], "class": m["evidence_class"], "source": m["source"]})
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "operational": {
            "offers": offers_doc["summary"],
            "offer_blockers": dict(blocked_reasons.most_common()),
            "platforms": readiness,
            "jobs_by_state": dict(Counter(j["state"] for j in jobs)),
            "jobs_by_platform": dict(Counter(j["platform"] for j in jobs)),
            "jobs_by_arm": dict(Counter(j.get("arm") for j in jobs)),
            "qa_failure_reasons": dict(qa_fail.most_common()),
            "awaiting_approval": [j["job_id"] for j in jobs if j["state"] == "QA_PASSED"],
            "stuck_or_retrying": stuck,
            "published_verified": [{"job": j["job_id"], "url": j.get("verified_url")} for j in jobs if j["state"] == "PUBLISHED_VERIFIED"],
            "manual_posts_unverified": [{"job": j["job_id"], "url": j.get("post_url")} for j in jobs if j["state"] == "MANUAL_POSTED_UNVERIFIED"],
        },
        "commercial": {
            "metrics": commercial or "NO REAL METRICS RECORDED",
            "verified_revenue_cents": sum(m["value"] for m in metrics if m["metric"] == "net_revenue_cents"
                                          and m["evidence_class"] == "OBSERVED") if metrics else 0,
            "note": "Traffic to the public site is unmeasured (GitHub Pages has no beacon receiver). Gumroad sales carry "
                    "their own referrer; no social-attributed sale exists.",
        },
        "next_actions": next_actions(readiness, jobs, blocked_reasons),
    }


def next_actions(readiness, jobs, blocked_reasons) -> list:
    acts = []
    awaiting = sum(1 for j in jobs if j["state"] == "QA_PASSED")
    if awaiting:
        acts.append(f"Founder: review {awaiting} QA-passed drafts and approve the ones to post (manual hand-off).")
    for p, r in readiness.items():
        if r["state"] != "PUBLISH_VERIFIED":
            acts.append(f"{r['name']}: {r['why']}.")
    if blocked_reasons:
        top, n = blocked_reasons.most_common(1)[0]
        acts.append(f"Largest offer blocker ({n}): {top}.")
    return acts


def render_md(d: dict) -> str:
    o, c = d["operational"], d["commercial"]
    lines = [f"# Distribution dashboard (generated {d['generated_at']})", "",
             "Generated by `scripts/distribution_cycle.py` from recorded files only. Operational state first; commercial evidence second.", "",
             "## Platforms", "", "| Platform | State | Publish mode | Why |", "|---|---|---|---|"]
    lines += [f"| {r['name']} | {r['state']} | {r['publish_mode']} | {r['why']} |" for r in o["platforms"].values()]
    s = o["offers"]
    lines += ["", "## Offers", "", f"Total {s['total']}; eligibility {s['by_eligibility']}; by arm {s['by_arm']}.", "",
              "| Blocker | Offers |", "|---|---|"] + [f"| {k} | {v} |" for k, v in o["offer_blockers"].items()]
    lines += ["", "## Campaign jobs", "", f"By state: {o['jobs_by_state'] or 'none'}", "",
              f"By platform: {o['jobs_by_platform'] or 'none'}", "", f"By arm: {o['jobs_by_arm'] or 'none'}", "",
              f"QA failure reasons: {o['qa_failure_reasons'] or 'none'}", "",
              f"Awaiting approval: {len(o['awaiting_approval'])}. Stuck or retrying: {len(o['stuck_or_retrying'])}.", "",
              f"Published and verified: {len(o['published_verified'])}. Posted by hand, unverified: {len(o['manual_posts_unverified'])}.",
              "", "## Commercial evidence", "",
              f"Metrics: {c['metrics'] if isinstance(c['metrics'], str) else json.dumps(c['metrics'])}", "",
              f"Verified revenue from social distribution: ${c['verified_revenue_cents'] / 100:.2f}", "", c["note"], "",
              "## Next actions", ""] + [f"- {a}" for a in d["next_actions"]]
    return "\n".join(lines) + "\n"


def write(d, json_path=OUT_JSON, md_path=OUT_MD):
    Path(json_path).parent.mkdir(parents=True, exist_ok=True)
    Path(json_path).write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    Path(md_path).parent.mkdir(parents=True, exist_ok=True)
    Path(md_path).write_text(render_md(d), encoding="utf-8")


def real_metrics():
    return tracking.read_metrics(tracking.REAL_LEDGER)
