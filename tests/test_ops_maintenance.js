// Regression test for the standing-charter continuous-improvement
// follow-up: scripts/ops_maintenance.js used to rotate only
// logs/service_layer.log. factory_loop.log and inspections.log are real,
// unbounded, growing root-level logs it never covered (zero-assumption
// audit, Section C). Generalized rotateLogIfNeeded() into a single
// parameterized function every log shares, called for all three via
// rotateAllKnownLogs(). Uses temp files, never the real logs.
//
//   node --test tests/test_ops_maintenance.js

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { rotateLogIfNeeded, cleanupOldReports, isGeneratedReport } = require('../scripts/ops_maintenance.js');

function tempLogPath() {
  return path.join(os.tmpdir(), `test_ops_maintenance_${process.pid}_${Date.now()}_${Math.random().toString(36).slice(2)}.log`);
}

test('rotateLogIfNeeded: missing file -> no-op, never throws', () => {
  const p = tempLogPath();
  const result = rotateLogIfNeeded(p, 'test', 1024, false);
  assert.equal(result.rotated, false);
  assert.equal(result.reason, 'missing');
});

test('rotateLogIfNeeded: below threshold -> no-op, dry run never touches the file', () => {
  const p = tempLogPath();
  fs.writeFileSync(p, 'small content');
  try {
    const result = rotateLogIfNeeded(p, 'test', 1024 * 1024, false);
    assert.equal(result.rotated, false);
    assert.equal(result.reason, 'below_threshold');
    assert.ok(fs.existsSync(p), 'file must be untouched below threshold');
  } finally {
    fs.rmSync(p, { force: true });
  }
});

test('rotateLogIfNeeded: over threshold, dry run -> reports but does not actually rotate', () => {
  const p = tempLogPath();
  fs.writeFileSync(p, 'x'.repeat(2000));
  try {
    const result = rotateLogIfNeeded(p, 'test', 1000, false); // apply=false (default)
    assert.equal(result.rotated, false, 'dry run must never actually rotate');
    assert.equal(result.reason, 'over_threshold');
    assert.ok(fs.existsSync(p), 'dry run must leave the original file exactly as it was');
    assert.equal(fs.statSync(p).size, 2000);
  } finally {
    fs.rmSync(p, { force: true });
  }
});

test('rotateLogIfNeeded: over threshold, --apply -> real rotation, original file truncated', () => {
  const p = tempLogPath();
  fs.writeFileSync(p, 'x'.repeat(2000));
  let archivePath;
  try {
    const result = rotateLogIfNeeded(p, 'test-rotate', 1000, true);
    assert.equal(result.rotated, true);
    archivePath = result.archivePath;
    assert.ok(fs.existsSync(archivePath), 'a real archive file must be created');
    assert.equal(fs.statSync(archivePath).size, 2000, 'the archive must contain the real, full original content');
    assert.ok(fs.existsSync(p), 'the original log path must still exist, now empty');
    assert.equal(fs.statSync(p).size, 0, 'the original log must be truncated to empty after rotation, not deleted');
  } finally {
    fs.rmSync(p, { force: true });
    if (archivePath) fs.rmSync(archivePath, { force: true });
  }
});

// REAL INCIDENT, 2026-10-28: cleanupOldReports() used to delete every
// reports/*.md beyond the newest 10, and one --apply run removed 591 files --
// 112 tracked (restored from git) and ~479 untracked authored deliverables
// (permanently lost). reports/ is not a disposable cache. These two tests pin
// the fix: only names the factory's own scheduled reports generate may ever be
// removed, and a hand-written report survives cleanup no matter how old it is.
test('isGeneratedReport: only scheduled-report names are considered disposable', () => {
  for (const name of ['EXECUTIVE_BRIEF_2026-10-27.md', 'EVOLUTION_2026-10-27.md', 'AI_DOCTOR_2026-10-27.md',
    'DEPARTMENT_HEALTH_2026-10-27.md', 'WEEK_2026-10-25.md', 'GALAXY_EVOLUTION_2026-10.md',
    'ARCHITECTURE_REVIEW_2026-Q4.md', 'ANNUAL_STRATEGIC_REVIEW_2026.md', 'executive_report_20261011T000813Z.md']) {
    assert.equal(isGeneratedReport(name), true, name + ' is generated by a scheduled report and may be pruned');
  }
  for (const name of ['CYCLE116_BASELINE.md', 'REALITY_LEDGER_2026-07-31.md', 'ENTERPRISE_TRUTH_AUDIT_REPORT_2026-07-31.md',
    'TECHNICAL_DEBT_REGISTER_2026-07-31.md', 'FOUNDER_BATCH.md', 'LISTINGS_TO_UNPUBLISH.md', 'EXECUTIVE_BRIEF_draft.md']) {
    assert.equal(isGeneratedReport(name), false, name + ' is authored evidence and must never be pruned');
  }
});

test('cleanupOldReports: never deletes a non-generated report, however old', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'test_ops_reports_'));
  try {
    const authored = path.join(dir, 'CYCLE116_BASELINE.md');
    fs.writeFileSync(authored, 'authored evidence');
    const old = new Date('2020-01-01T00:00:00Z');
    fs.utimesSync(authored, old, old);
    for (let i = 0; i < 4; i++) {
      const p = path.join(dir, 'EXECUTIVE_BRIEF_2026-10-0' + (i + 1) + '.md');
      fs.writeFileSync(p, 'generated');
      const t = new Date(Date.UTC(2026, 9, i + 1));
      fs.utimesSync(p, t, t);
    }
    cleanupOldReports(true, dir, 2);
    assert.ok(fs.existsSync(authored), 'the oldest file in the directory is authored and must survive');
    const left = fs.readdirSync(dir).filter(f => f.endsWith('.md'));
    assert.equal(left.length, 3, 'retention=2 prunes only the 2 oldest generated reports, keeping 2 + the authored one');
    assert.ok(left.includes('CYCLE116_BASELINE.md'));
    assert.ok(!left.includes('EXECUTIVE_BRIEF_2026-10-01.md'), 'oldest generated report is pruned');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
