#!/usr/bin/env python3
"""Daily tool-page refresh for factory_loop.js (2026-10-29).

After the registry rebuild, regenerate the site pages for every published
spreadsheet tool (books/_batch15_src/site_pages.py: one page per product that
has a verified Gumroad URL, tools.html and sitemap entries). The loop's
site_publish step then publishes whatever changed.

Why: batch-15 pages were generated by hand on 2026-10-24 and never published;
ten live products had no site page for five days. Nothing regenerated them.

The generator lives in the private product sources (git-ignored); when it is
absent this step says so instead of failing.

    python scripts/tool_pages_daily.py --once
"""
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "books" / "_batch15_src" / "site_pages.py"
STATE = ROOT / "data" / "tool_pages_daily_state.json"


def _run(timeout_s=300):
    r = subprocess.run([sys.executable, str(GENERATOR)], cwd=str(ROOT), capture_output=True, text=True,
                       encoding="utf-8", errors="replace", timeout=timeout_s)
    if r.returncode != 0:
        raise RuntimeError(f"site_pages exited {r.returncode}: {r.stderr.strip()[-200:]}")
    return json.loads(r.stdout.strip().splitlines()[-1])


def _git(root, *args):
    return subprocess.run(["git", *args], cwd=str(root), capture_output=True, text=True, encoding="utf-8", errors="replace")


def commit_generated(root=ROOT):
    """Commit the pages the generator just wrote, and nothing else (2026-11-06).

    The generator only writes files; the loop's site_publish step publishes COMMITTED site changes, so a new tool page
    never reached the site on its own (found while checking the path for B17-001). Only `tool-*.html`, `tools.html`
    and added `/tool-` lines of sitemap.xml are committed; any other change in the tree is left exactly as it is, and a
    sitemap with removed or unrelated lines is left uncommitted for review."""
    st = _git(root, "status", "--porcelain", "--", "customer_site/tools.html", "customer_site/tool-*.html", "sitemap.xml")
    paths = []
    for line in st.stdout.splitlines():
        path = line[3:].strip().strip('"')
        if path == "sitemap.xml":
            diff = _git(root, "diff", "-U0", "--", "sitemap.xml").stdout.splitlines()
            added = [l for l in diff if l.startswith("+") and not l.startswith("+++")]
            removed = [l for l in diff if l.startswith("-") and not l.startswith("---")]
            if removed or not added or any("/tool-" not in l for l in added):
                continue  # not purely new tool-page entries: leave for review
        paths.append(path)
    if not paths:
        return {"committed": 0, "paths": []}
    add = _git(root, "add", "--", *paths)
    if add.returncode != 0:
        return {"committed": 0, "paths": paths, "error": add.stderr.strip()[:160]}
    msg = f"Site: tool pages generated by tool_pages_daily ({len(paths)} file(s), nothing else included)"
    c = _git(root, "commit", "-q", "-m", msg, "--", *paths)
    if c.returncode != 0:
        return {"committed": 0, "paths": paths, "error": (c.stderr or c.stdout).strip()[:160]}
    return {"committed": len(paths), "paths": paths}


def run_once(today=None, state_path=STATE, generator=GENERATOR, runner=None, committer=None):
    today = today or datetime.now(timezone.utc).date().isoformat()
    try:
        last = json.loads(Path(state_path).read_text(encoding="utf-8")).get("last_day")
    except (OSError, ValueError):
        last = None
    if last == today:
        return {"action": "none", "detail": f"tool pages already refreshed for {today}"}
    if runner is None and not Path(generator).exists():
        return {"action": "none", "detail": "generator not present (private sources not on this machine)"}
    try:
        out = (runner or _run)()
    except Exception as e:
        return {"action": "failed", "detail": f"{type(e).__name__}: {str(e)[:200]}"}
    tmp = Path(str(state_path) + ".tmp")
    tmp.write_text(json.dumps({"last_day": today, "result": out}), encoding="utf-8")
    tmp.replace(state_path)
    added = out.get("sitemap_added", 0)
    skipped = out.get("skipped_unpublished") or []
    try:
        committed = (committer or commit_generated)()
    except Exception as e:  # a git problem must not fail the page refresh
        committed = {"committed": 0, "error": f"{type(e).__name__}: {str(e)[:120]}"}
    note = f"; {committed['committed']} file(s) committed for publishing" if committed.get("committed") else (
        f"; commit problem: {committed['error']}" if committed.get("error") else "")
    return {"action": "updated" if (added or committed.get("committed")) else "none",
            "detail": f"{out.get('pages')} tool pages, {added} new in sitemap, {len(skipped)} unpublished skipped{note}"}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--once" not in argv:
        print(__doc__)
        return 2
    print(json.dumps(run_once()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
