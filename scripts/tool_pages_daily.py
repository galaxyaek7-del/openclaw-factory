#!/usr/bin/env python3
"""Daily tool-page refresh for factory_loop.js (2026-10-29).

After the registry rebuild, regenerate the site pages for every published
spreadsheet tool (books/_batch15_src/site_pages.py: one page per product that
has a verified Gumroad URL, tools.html and sitemap entries). The loop's
site_publish step then publishes whatever changed.

Why: batch-15 pages were generated by hand on 2026-10-24 and never published;
ten live products had no site page for five days. Nothing regenerated them.

The generator lives in the private product sources (git-ignored); when it is
absent this step says so instead of failing.

    python scripts/tool_pages_daily.py --once
"""
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "books" / "_batch15_src" / "site_pages.py"
STATE = ROOT / "data" / "tool_pages_daily_state.json"


def _run(timeout_s=300):
    r = subprocess.run([sys.executable, str(GENERATOR)], cwd=str(ROOT), capture_output=True, text=True,
                       encoding="utf-8", errors="replace", timeout=timeout_s)
    if r.returncode != 0:
        raise RuntimeError(f"site_pages exited {r.returncode}: {r.stderr.strip()[-200:]}")
    return json.loads(r.stdout.strip().splitlines()[-1])


def run_once(today=None, state_path=STATE, generator=GENERATOR, runner=None):
    today = today or datetime.now(timezone.utc).date().isoformat()
    try:
        last = json.loads(Path(state_path).read_text(encoding="utf-8")).get("last_day")
    except (OSError, ValueError):
        last = None
    if last == today:
        return {"action": "none", "detail": f"tool pages already refreshed for {today}"}
    if runner is None and not Path(generator).exists():
        return {"action": "none", "detail": "generator not present (private sources not on this machine)"}
    try:
        out = (runner or _run)()
    except Exception as e:
        return {"action": "failed", "detail": f"{type(e).__name__}: {str(e)[:200]}"}
    tmp = Path(str(state_path) + ".tmp")
    tmp.write_text(json.dumps({"last_day": today, "result": out}), encoding="utf-8")
    tmp.replace(state_path)
    added = out.get("sitemap_added", 0)
    skipped = out.get("skipped_unpublished") or []
    return {"action": "updated" if added else "none",
            "detail": f"{out.get('pages')} tool pages, {added} new in sitemap, {len(skipped)} unpublished skipped"}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if "--once" not in argv:
        print(__doc__)
        return 2
    print(json.dumps(run_once()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
