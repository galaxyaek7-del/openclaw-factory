#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Production check of the visit counter: four statuses, reported separately (2026-11-07). Read-only (HTTP GET only).

    python scripts/verify_counter_production.py [--json]

  deployment        the PRODUCTION copy of gf-pageview.js carries a valid counter code (OBSERVED from the live file)
  script_loading    the production pages reference gf-pageview.js and the counter script (count.js) answers HTTP 200
  tracking_event    UNKNOWN from here: a pageview is only produced by a real browser running the page. This tool never claims it.
  dashboard         UNKNOWN from here: the dashboard needs the founder's login (or a read-only API token). Never claimed.

Fail-closed: any network problem is UNKNOWN, never OK. Nothing is fabricated: no traffic is generated by this tool.
"""
from __future__ import annotations

import json
import re
import sys

BASE = "https://galaxyaek7-del.github.io/openclaw-factory/"
SAMPLE = ["customer_site/products.html", "customer_site/tools.html", "customer_site/index.html", "customer_site/tool-food-truck-cost-estimator.html"]
CODE_RE = re.compile(r"var GF_COUNTER_CODE = '([^']*)'")


def get(url, timeout=20):
    import requests
    r = requests.get(url, timeout=timeout, headers={"User-Agent": "galaxy-forge-verify/1.0"})
    return r.status_code, r.text


def check(fetch=get, sample=SAMPLE):
    out = {"deployment": {"status": "UNKNOWN", "class": "UNKNOWN", "detail": ""}, "script_loading": {"status": "UNKNOWN", "class": "UNKNOWN", "detail": ""},
           "tracking_event": {"status": "UNKNOWN", "class": "UNKNOWN", "detail": "needs a real browser pageview; not generated or claimed by this tool"},
           "dashboard": {"status": "UNKNOWN", "class": "UNKNOWN", "detail": "needs the founder's login or a read-only API token; not claimed"}}
    code = None
    try:
        st, body = fetch(BASE + "customer_site/assets/gf-pageview.js")
        m = CODE_RE.search(body) if st == 200 else None
        code = m.group(1) if m and re.match(r"^[a-z0-9-]{2,40}$", m.group(1)) else None
        if st != 200:
            out["deployment"].update(detail=f"production gf-pageview.js answered HTTP {st}")
        elif code:
            out["deployment"].update(status="DEPLOYED", **{"class": "OBSERVED"}, detail=f"production gf-pageview.js has counter code '{code}'")
        else:
            out["deployment"].update(status="NOT_DEPLOYED", **{"class": "OBSERVED"}, detail="production gf-pageview.js has no counter code yet (publish pending)")
    except Exception as e:  # noqa: BLE001
        out["deployment"]["detail"] = f"{type(e).__name__}: could not read the production file"
    try:
        refs, bad = 0, []
        for p in sample:
            st, body = fetch(BASE + p)
            if st == 200 and "gf-pageview.js" in body:
                refs += 1
            else:
                bad.append(f"{p} (HTTP {st}{'' if st != 200 else ', no loader'})")
        st2, _ = fetch("https://gc.zgo.at/count.js")
        ok = refs == len(sample) and st2 == 200
        out["script_loading"].update(status="LOADABLE" if ok and code else ("PAGES_OK_COUNTER_OFF" if ok else "PROBLEM"), **{"class": "OBSERVED"},
                                     detail=f"{refs}/{len(sample)} sample production pages reference gf-pageview.js; count.js HTTP {st2}" + (f"; problems: {bad}" if bad else ""))
    except Exception as e:  # noqa: BLE001
        out["script_loading"]["detail"] = f"{type(e).__name__}: could not fetch production pages"
    return out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    r = check()
    if "--json" in argv:
        sys.stdout.write(json.dumps(r, ensure_ascii=False, indent=1) + "\n")
    else:
        sys.stdout.buffer.write(("\n".join(f"{k:15} {v['status']:22} [{v['class']}] {v['detail']}" for k, v in r.items()) + "\n").encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
