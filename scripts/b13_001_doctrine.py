def changed_stats() -> dict:
    paths = ["scripts", "tests", "books/batch13", "books/batch12/B12-004_meeting_method_guide.pdf",
             "native_workbook_qa.py"]
    out = subprocess.run(["git", "diff", "--numstat", "HEAD", "--"] + paths,
                         cwd=ROOT, capture_output=True, text=True)
    ins = dele = files = 0
    for line in out.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) >= 3:
            files += 1
            ins += int(parts[0]) if parts[0].isdigit() else 0
            dele += int(parts[1]) if parts[1].isdigit() else 0
    for new in list((ROOT / "books" / "batch13").glob("*")):
        if new.is_file():
            files += 1
            try:
                ins += len(new.read_bytes().splitlines())
            except OSError:
                pass
    return {"files": files, "insertions": ins, "deletions": dele}


